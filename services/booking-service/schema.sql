-- booking_db schema (owner: Booking service). Run as booking_user:
--   mysql -u booking_user -pbooking_pass booking_db < schema.sql
-- The service also creates these tables on first start if they are missing.
-- Keep in step with app/db.py.
-- Other services' data is referred to by plain values only (seat_no, payment_id): no cross-DB keys.

CREATE TABLE IF NOT EXISTS bookings (
  id              VARCHAR(36)   NOT NULL,             -- UUID generated by Booking before calling Seat
  event_id        INT           NOT NULL,             -- ID owned by Seat service (no FK)
  customer_email  VARCHAR(255)  NOT NULL,
  amount          DECIMAL(10,2) NOT NULL,             -- seats x SEAT_PRICE, computed by the server
  status          VARCHAR(20)   NOT NULL,             -- HELD | CONFIRMED | CANCELLED | EXPIRED
  hold_expires_at DATETIME      NOT NULL,             -- UTC
  pay_lock        VARCHAR(100)  NULL,                 -- Idempotency-Key of the payment in flight
  pay_locked_at   DATETIME      NULL,
  payment_id      VARCHAR(64)   NULL,                 -- ID owned by Payment service (no FK)
  created_at      DATETIME      NOT NULL,
  updated_at      DATETIME      NOT NULL,
  PRIMARY KEY (id),
  INDEX ix_bookings_status_expiry (status, hold_expires_at)
);

CREATE TABLE IF NOT EXISTS booking_seats (
  booking_id VARCHAR(36) NOT NULL,
  seat_no    VARCHAR(10) NOT NULL,                    -- seat label owned by Seat service (no FK)
  PRIMARY KEY (booking_id, seat_no),
  FOREIGN KEY (booking_id) REFERENCES bookings (id)   -- same database, so a FK is fine
);

-- Challenge 2 / BR4: the PRIMARY KEY on idem_key is what lets only ONE of two
-- simultaneous identical pay requests through.
CREATE TABLE IF NOT EXISTS idempotency_keys (
  idem_key      VARCHAR(100) NOT NULL,
  booking_id    VARCHAR(36)  NOT NULL,
  request_hash  VARCHAR(64)  NOT NULL,                -- SHA-256 of method|path|body
  status        VARCHAR(20)  NOT NULL,                -- IN_PROGRESS | DONE
  response_code INT          NULL,
  response_body TEXT         NULL,
  created_at    DATETIME     NOT NULL,
  updated_at    DATETIME     NOT NULL,
  PRIMARY KEY (idem_key)
);
